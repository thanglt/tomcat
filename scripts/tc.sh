#!/usr/bin/env bash
# Usage: tc.sh <start|stop|restart|status|log|sync|conf|clearlog|webapps> [name|all] [days]
#        tc.sh reload [name|all] [context ...]   redeploy context (vd cdn) không cần restart — dùng sau khi build lại module
#        tc.sh list | wrappers
# START_WAIT=<giây> (mặc định 120, 0 = không chờ xác nhận khởi động)
set -uo pipefail
TC_ROOT="${TC_ROOT:-$HOME/tomcat}"
export CATALINA_HOME="${CATALINA_HOME:-$TC_ROOT/apache-tomcat-10.1.57}"
INSTANCES="$TC_ROOT/instance"
SCRIPTS_DIR="$(cd "$(dirname "$0")" && pwd)"
MONITOR_FILE="$SCRIPTS_DIR/monitor-instances-tomcat.sh"
STOP_TIMEOUT="${STOP_TIMEOUT:-30}"
START_WAIT="${START_WAIT:-120}"
GEN_MARK="# GENERATED by tc.sh - do not edit, use override/"
ACTION="${1:-}"; TARGET="${2:-all}"; DAYS="${3:-0}"; RELOAD_CTX=""

list_names() { for d in "$INSTANCES"/*/; do [[ -f "$d/instance.env" ]] && basename "$d"; done; }
# Thứ tự khi chạy "all": START_ORDER trong instance.env (số nhỏ chạy trước, mặc định 50, rồi theo tên).
# stop chạy ngược lại. START_ORDER < 10 = instance nền tảng (vd liquibase): nếu start thất bại thì dừng, không start tiếp.
order_of() { local v; v=$(sed -n 's/^START_ORDER=//p' "$INSTANCES/$1/instance.env" | tr -d '"' | head -1); [[ "$v" =~ ^[0-9]+$ ]] && echo "$v" || echo 50; }
ordered_names() { local n; for n in $(list_names); do printf '%05d %s\n' "$(order_of "$n")" "$n"; done | sort | awk '{print $2}'; }
pid_of() { local f="$INSTANCES/$1/temp/tomcat.pid"; [[ -f "$f" ]] && cat "$f"; }
is_running() { local p; p=$(pid_of "$1") && [[ -n "$p" ]] && kill -0 "$p" 2>/dev/null; }
skip_file() { case "$1" in *.orig|*.bak*|*~|README.txt|setenv.sh) return 0;; esac; return 1; }

# Ghi file kiểu atomic (ghi file tạm cùng thư mục rồi mv) để không làm hỏng
# script đang chạy (vd monitor/agent đang chạy đúng lúc tc-create cập nhật nó)
atomic_write() { local dst="$1" tmp="$1.tmp.$$"; cat > "$tmp" && chmod 755 "$tmp" && mv -f "$tmp" "$dst"; }

# ---------- script prefix + monitor ----------
write_wrapper() { printf '#!/usr/bin/env bash\nexec "$(dirname "$0")/tc.sh" %s "$@"\n' "$2" | atomic_write "$1"; }

# Cập nhật khối BEGIN/END INSTANCES trong monitor; giữ health_path + on/off đã sửa
update_monitor() {
  [[ -f "$MONITOR_FILE" ]] || { echo "(chưa có $MONITOR_FILE - bỏ qua cập nhật monitor)"; return 0; }
  local blk n old port hp en cnt=0
  blk=$(mktemp "${TMPDIR:-/tmp}/tc-monitor-blk.XXXXXX")
  echo "INSTANCES_CONF=(" > "$blk"
  for n in $(list_names); do
    port=$(sed -n 's/^HTTP_PORT=//p' "$INSTANCES/$n/instance.env" | head -1)
    old=$(sed -n '/^# BEGIN INSTANCES/,/^# END INSTANCES/p' "$MONITOR_FILE" | sed -n "s/^ *\"\($n|[^\"]*\)\".*/\1/p" | head -1)
    hp="/"; en="on"
    if [[ -n "$old" ]]; then IFS='|' read -r _ _ hp en <<<"$old"; fi
    echo "  \"$n|$port|${hp:-/}|${en:-on}\"" >> "$blk"; cnt=$((cnt + 1))
  done
  echo ")" >> "$blk"
  awk -v blk="$blk" '
    /^# BEGIN INSTANCES/ { print; print "# name|http_port|health_path|on/off"; while ((getline l < blk) > 0) print l; skip=1; next }
    /^# END INSTANCES/   { skip=0 }
    !skip { print }' "$MONITOR_FILE" | atomic_write "$MONITOR_FILE"
  rm -f "$blk"
  echo "Đã cập nhật monitor: $cnt instance"
}

gen_wrappers() {
  local n a
  for n in $(list_names); do
    for a in start stop restart status log conf clearlog; do write_wrapper "$SCRIPTS_DIR/$a-$n.sh" "$a $n"; done
  done
  for a in start stop restart status clearlog; do write_wrapper "$SCRIPTS_DIR/$a-all.sh" "$a all"; done
  echo "Đã sinh script prefix trong $SCRIPTS_DIR"
  update_monitor
  # Cloudflare Tunnel: sinh lại khối ingress (áp vào config cloudflared bằng: tc-tunnel.sh apply, chạy trên Mac)
  if [[ -f "$TC_ROOT/cloudflare/tunnel.env" && -x "$SCRIPTS_DIR/tc-tunnel.sh" ]]; then
    TC_ROOT="$TC_ROOT" "$SCRIPTS_DIR/tc-tunnel.sh" gen >/dev/null && echo "Đã sinh ingress Cloudflare: $TC_ROOT/cloudflare/ingress-tomcat.yml (chạy tc-tunnel.sh apply trên Mac)"
  fi
}

# ---------- webapp: khai báo trong apps/, deploy bằng Context XML (tự reload khi code đổi) ----------
# - instance/<name>/apps/<context>  : symlink -> thư mục exploded (vd .../target/webapp-current)
# - $TC_ROOT/shared-webapps/<context>: webapp dùng chung cho MỌI instance (vd cdn), trừ khi instance đã khai báo
#   cùng context trong apps/ hoặc bỏ qua bằng SHARED_WEBAPPS_SKIP="cdn ..." trong instance.env
# Mỗi webapp được sinh thành conf/Catalina/localhost/<context>.xml:
#   reloadable=AUTO_RELOAD (mặc định true)  -> Tomcat reload context khi WEB-INF/classes hoặc WEB-INF/lib thay đổi
#   DEV_CLASSES=true (mặc định)            -> mount thêm <module>/target/classes (IDE compile) vào /WEB-INF/classes
#   STATIC_CACHE_TTL (ms, mặc định 2000)    -> file tĩnh (html/js/css) đổi là thấy sau tối đa N ms, không cần reload
SHARED_DIR="$TC_ROOT/shared-webapps"
CTX_MARK="<!-- GENERATED by tc.sh webapps"
xml_esc() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/"/\&quot;/g' -e 's/</\&lt;/g'; }

write_context() {   # <name> <context> <docBase>
  local name="$1" ctx="$2" target="$3" dir f classes pre=""
  dir="$INSTANCES/$name/conf/Catalina/localhost"; mkdir -p "$dir"
  f="$dir/$ctx.xml"
  classes="$(dirname "$target")/classes"
  if [[ "${DEV_CLASSES:-true}" == "true" && "$target" == */target/webapp-current && -d "$classes" ]]; then
    pre="    <PreResources className=\"org.apache.catalina.webresources.DirResourceSet\" base=\"$(xml_esc "$classes")\" webAppMount=\"/WEB-INF/classes\"/>"
  fi
  [[ -d "$target" || -n "${TC_IN_VM:-}" ]] || echo "  [$name] CẢNH BÁO: /$ctx -> $target chưa tồn tại (chưa build?)"
  {
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo "$CTX_MARK — khai báo ở apps/ hoặc shared-webapps/, chỉnh AUTO_RELOAD/DEV_CLASSES/STATIC_CACHE_TTL trong instance.env -->"
    echo "<Context docBase=\"$(xml_esc "$target")\" reloadable=\"${AUTO_RELOAD:-true}\">"
    echo "  <Resources cachingAllowed=\"true\" cacheTtl=\"${STATIC_CACHE_TTL:-2000}\">"
    [[ -n "$pre" ]] && echo "$pre"
    echo "  </Resources>"
    echo "</Context>"
  } | atomic_write "$f"
}

# ROOT_REDIRECT="/admin/" trong instance.env -> sinh context ROOT (RewriteValve) redirect 302
#   / -> /admin/ , /x?y -> /admin/x?y  (dùng cho <instance>.<domain> qua Cloudflare Tunnel)
write_root_redirect() {   # <name> <target>
  local name="$1" t="${2%/}" dir
  dir="$INSTANCES/$name/root-redirect"; mkdir -p "$dir/WEB-INF"
  printf '# GENERATED by tc.sh (ROOT_REDIRECT trong instance.env)\nRewriteRule ^/(.*)$ %s/$1 [R=302,L]\n' "$t" | atomic_write "$dir/WEB-INF/rewrite.config"
  {
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo "$CTX_MARK — ROOT_REDIRECT=$2 trong instance.env -->"
    echo "<Context docBase=\"$(xml_esc "$dir")\" reloadable=\"false\">"
    echo '  <Valve className="org.apache.catalina.valves.rewrite.RewriteValve"/>'
    echo "</Context>"
  } | atomic_write "$INSTANCES/$name/conf/Catalina/localhost/ROOT.xml"
}

sync_webapps() {    # <name>
  local name="$1" base="$INSTANCES/$1" apps="$INSTANCES/$1/apps" l s ctx f declared=" " skip
  mkdir -p "$apps" "$base/webapps"
  # chuyển symlink cũ trong webapps/ sang apps/ (webapps/ chỉ còn webapp thật, vd ROOT copy)
  for l in "$base/webapps"/*; do
    [[ -L "$l" ]] || continue; ctx=$(basename "$l")
    if [[ -e "$apps/$ctx" || -L "$apps/$ctx" ]] || \
       { [[ -L "$SHARED_DIR/$ctx" ]] && [[ "$(readlink "$SHARED_DIR/$ctx")" == "$(readlink "$l")" ]]; }; then
      mv -f "$l" "$base/.webapps-old-$ctx"     # trùng apps/ hoặc là link webapp dùng chung cũ
    else mv "$l" "$apps/$ctx"; echo "  [$name] chuyển webapps/$ctx -> apps/$ctx"; fi
  done
  # webapp riêng của instance
  for l in "$apps"/*; do
    [[ -L "$l" || -d "$l" ]] || continue; ctx=$(basename "$l")
    write_context "$name" "$ctx" "$( [[ -L "$l" ]] && readlink "$l" || echo "$l" )"; declared+="$ctx "
  done
  # webapp dùng chung
  skip=" ${SHARED_WEBAPPS_SKIP:-} "
  if [[ -d "$SHARED_DIR" ]]; then
    for s in "$SHARED_DIR"/*; do
      [[ -L "$s" || -d "$s" ]] || continue; ctx=$(basename "$s")
      [[ "$declared" == *" $ctx "* || "$skip" == *" $ctx "* ]] && continue
      write_context "$name" "$ctx" "$( [[ -L "$s" ]] && readlink "$s" || echo "$s" )"; declared+="$ctx "
    done
  fi
  # redirect / -> ROOT_REDIRECT (nếu chưa có apps/ROOT hoặc webapps/ROOT thật)
  if [[ -n "${ROOT_REDIRECT:-}" && "$declared" != *" ROOT "* && ! -d "$base/webapps/ROOT" ]]; then
    write_root_redirect "$name" "$ROOT_REDIRECT"; declared+="ROOT "
  fi
  # gỡ Context XML do script sinh nhưng không còn được khai báo
  for f in "$base/conf/Catalina/localhost"/*.xml; do
    [[ -f "$f" ]] || continue; ctx=$(basename "$f" .xml)
    [[ "$declared" == *" $ctx "* ]] && continue
    grep -qF "$CTX_MARK" "$f" || continue
    rm -f "$f" 2>/dev/null || mv -f "$f" "$f.disabled"
    echo "  [$name] gỡ /$ctx (không còn khai báo)"
  done
  for ctx in $declared; do
    [[ -d "$base/webapps/$ctx" ]] && echo "  [$name] CẢNH BÁO: webapps/$ctx là thư mục thật, Context XML /$ctx sẽ được dùng thay"
  done
}

show_webapps() {
  local name="$1" f d r c
  for f in "$INSTANCES/$name/conf/Catalina/localhost"/*.xml; do
    [[ -f "$f" ]] || continue
    d=$(sed -n 's/.*docBase="\([^"]*\)".*/\1/p' "$f" | head -1); r=$(sed -n 's/.*reloadable="\([^"]*\)".*/\1/p' "$f" | head -1)
    grep -q 'webAppMount="/WEB-INF/classes"' "$f" && c="+target/classes" || c=""
    printf "  /%-12s reload=%-5s %s %s\n" "$(basename "$f" .xml)" "$r" "$d" "$c"
  done
}

# ---------- conf ----------
sync_conf() {
  local base="$1" conf="$1/conf" ovr="$1/override" src f dst o
  mkdir -p "$conf" "$ovr"
  if [[ -f "$base/bin/setenv.sh" ]]; then
    if [[ -e "$ovr/setenv.sh" ]]; then
      mv "$base/bin/setenv.sh" "$base/bin/setenv.sh.disabled"; echo "  bin/setenv.sh -> bin/setenv.sh.disabled"
    else
      mv "$base/bin/setenv.sh" "$ovr/setenv.sh"; echo "  chuyển bin/setenv.sh -> override/setenv.sh"
    fi
  fi
  for src in "$CATALINA_HOME"/conf/*; do
    [[ -f "$src" ]] || continue
    f=$(basename "$src"); skip_file "$f" && continue
    dst="$conf/$f"
    if [[ -f "$dst" && ! -L "$dst" ]] && ! head -1 "$dst" | grep -qF "$GEN_MARK"; then
      if cmp -s "$dst" "$src"; then rm -f "$dst"
      elif [[ ! -e "$ovr/$f" ]]; then mv "$dst" "$ovr/$f"; echo "  chuyển conf/$f -> override/$f"
      fi
    fi
    rm -f "$dst"
    if [[ -f "$ovr/$f" ]]; then
      if [[ "$f" == *.properties ]]; then
        { echo "$GEN_MARK"; cat "$src"; printf '\n# ---- override từ %s ----\n' "$ovr/$f"; cat "$ovr/$f"; } > "$dst"
      else
        ln -s "$ovr/$f" "$dst"
      fi
    else
      ln -s "$src" "$dst"
    fi
  done
  for o in "$ovr"/*; do
    [[ -f "$o" ]] || continue; f=$(basename "$o"); skip_file "$f" && continue
    [[ -e "$conf/$f" || -L "$conf/$f" ]] || ln -s "$o" "$conf/$f"
  done
}

show_conf() {
  local base="$1" p t f
  [[ -f "$base/override/setenv.sh" ]] && echo "  OVERRIDE  setenv.sh  (chung + override/setenv.sh)" || echo "  chung     setenv.sh"
  for p in "$base/conf"/*; do
    [[ -f "$p" ]] || continue; f=$(basename "$p")
    if [[ -L "$p" ]]; then t=$(readlink "$p")
      [[ "$t" == "$CATALINA_HOME"/* ]] && echo "  chung     $f" || echo "  OVERRIDE  $f  (thay toàn bộ)"
    else echo "  MERGE     $f  (chung + override/$f)"; fi
  done
}

# ---------- xác nhận khởi động ----------
wait_started() {
  local name="$1" out="$2" off="$3" i=0 new ms errs
  if (( START_WAIT == 0 )); then echo "[$name] đã gửi lệnh start → http://localhost:$HTTP_PORT"; return 0; fi
  echo "[$name] đang khởi động (chờ tối đa ${START_WAIT}s)..."
  while (( i < START_WAIT )); do
    sleep 1; i=$((i + 1))
    [[ -f "$out" ]] || continue
    new=$(tail -c +"$((off + 1))" "$out")
    ms=$(grep -oE 'Server startup in \[?[0-9.,]+\]? ?(milliseconds|ms)' <<<"$new" | grep -oE '[0-9][0-9.,]*' | tail -1)
    if [[ -n "$ms" ]]; then
      errs=$(grep -cE 'SEVERE|ERROR' <<<"$new")
      if (( errs > 0 )); then
        echo "[$name] KHỞI ĐỘNG XONG nhưng có $errs dòng lỗi (${ms} ms) → http://localhost:$HTTP_PORT"
        grep -E 'SEVERE|ERROR' <<<"$new" | tail -n 5 | cut -c1-300 | sed 's/^/    | /'
        return 1
      fi
      echo "[$name] KHỞI ĐỘNG THÀNH CÔNG trong ${ms} ms → http://localhost:$HTTP_PORT"
      return 0
    fi
    if ! is_running "$name"; then
      echo "[$name] KHỞI ĐỘNG THẤT BẠI — process đã dừng. 20 dòng cuối catalina.out:"
      tail -c +"$((off + 1))" "$out" | tail -n 20 | sed 's/^/    | /'
      return 1
    fi
  done
  echo "[$name] chưa thấy 'Server startup' sau ${START_WAIT}s (process vẫn chạy, xem log-$name.sh)"
  return 1
}

# ---------- log ----------
clear_logs() {
  local name="$1" base="$2" days="$3" logs="$2/logs" f open_files="" running=0 del=0 trunc=0 before after pid
  [[ "$days" =~ ^[0-9]+$ ]] || { echo "[$name] days phải là số: $days"; return 1; }
  [[ -d "$logs" ]] || { echo "[$name] không có thư mục logs"; return 0; }
  if is_running "$name"; then
    running=1; pid=$(pid_of "$name")
    # File Tomcat đang mở: theo lsof + catalina.out + mọi file ghi trong 24h qua (phòng khi lsof không có)
    open_files=$( { lsof -p "$pid" -Fn 2>/dev/null | sed -n 's/^n//p' | grep -F "/logs/"; find "$logs" -type f -mmin -1440; echo "$logs/catalina.out"; } | sort -u)
  fi
  before=$(du -sk "$logs" | cut -f1)
  local find_args=("$logs" -type f)
  (( days > 0 )) && find_args+=(-mtime "+$days")
  while IFS= read -r -d '' f; do
    if (( running )) && { grep -qxF "$f" <<<"$open_files" || grep -qxF "$logs/$(basename "$f")" <<<"$open_files"; }; then
      : > "$f"; trunc=$((trunc + 1))
    else
      rm -f "$f" && del=$((del + 1))
    fi
  done < <(find "${find_args[@]}" -print0)
  after=$(du -sk "$logs" | cut -f1)
  local scope="toàn bộ"; (( days > 0 )) && scope="cũ hơn $days ngày"
  echo "[$name] xóa log ($scope): xóa $del file, truncate $trunc file đang mở, giải phóng $(( (before - after) / 1024 )) MB"
}

# ---------- main ----------
run() {
  local name="$1" base="$INSTANCES/$1" out off
  [[ -f "$base/instance.env" ]] || { echo "[$name] không tồn tại"; return 1; }
  unset AUTO_RELOAD DEV_CLASSES STATIC_CACHE_TTL SHARED_WEBAPPS_SKIP EXTRA_OPTS ROOT_REDIRECT
  # shellcheck disable=SC1091
  source "$base/instance.env"
  export CATALINA_BASE="$base" CATALINA_PID="$base/temp/tomcat.pid"
  case "$ACTION" in
    start)
      rm -f "$base/.manual-stop"
      if is_running "$name"; then echo "[$name] đang chạy (pid $(pid_of "$name"))"; return 0; fi
      sync_conf "$base"; sync_webapps "$name"; rm -f "$CATALINA_PID"
      out="$base/logs/catalina.out"; off=0
      [[ -f "$out" ]] && off=$(wc -c < "$out" | tr -d ' ')
      "$CATALINA_HOME/bin/catalina.sh" start >/dev/null || { echo "[$name] catalina.sh start lỗi"; return 1; }
      wait_started "$name" "$out" "$off" ;;
    stop)
      date '+%F %T' > "$base/.manual-stop"
      if ! is_running "$name"; then echo "[$name] không chạy"; rm -f "$CATALINA_PID"; return 0; fi
      "$CATALINA_HOME/bin/catalina.sh" stop "$STOP_TIMEOUT" -force >/dev/null 2>&1
      rm -f "$CATALINA_PID"; echo "[$name] stopped" ;;
    restart) ACTION=stop run "$name"; sleep 2; ACTION=start run "$name" ;;
    status)
      if is_running "$name"; then printf "[%s] RUNNING pid=%s http=%s shutdown=%s logs=%s\n" "$name" "$(pid_of "$name")" "$HTTP_PORT" "$SHUTDOWN_PORT" "$(du -sh "$base/logs" 2>/dev/null | cut -f1)"
      else printf "[%s] STOPPED http=%s logs=%s\n" "$name" "$HTTP_PORT" "$(du -sh "$base/logs" 2>/dev/null | cut -f1)"; fi ;;
    sync) sync_conf "$base"; echo "[$name] đã sync (restart để áp dụng)" ;;
    webapps) sync_webapps "$name"; echo "[$name] webapps (restart để áp dụng thay đổi danh sách):"; show_webapps "$name" ;;
    conf)
      echo "[$name] http=$HTTP_PORT shutdown=$SHUTDOWN_PORT extra='$EXTRA_OPTS'"; show_conf "$base"
      is_running "$name" && echo "  JVM args: $(ps -o args= -p "$(pid_of "$name")" | tr ' ' '\n' | grep -E '^-(X|D(port|spring|file|user))' | tr '\n' ' ')" ;;
    clearlog) clear_logs "$name" "$base" "$DAYS" ;;
    log) tail -n 200 -f "$base/logs/catalina.out" ;;
    reload) reload_ctx "$name" "$base" ;;
  esac
}

# redeploy context bằng cách touch Context XML (Host autoDeploy=true quét ~10s/lần).
# Cần khi build lại làm đổi/xoá jar trong WEB-INF/lib (vd htmx.org-x.y.z.jar): Tomcat không tự reload được
# mà chỉ log "NoSuchFileException .../WEB-INF/lib/....jar" liên tục và context giữ danh sách jar cũ.
reload_ctx() {
  local name="$1" base="$2" dir="$2/conf/Catalina/localhost" ctxs="$RELOAD_CTX" c f out off t ok
  is_running "$name" || { echo "[$name] không chạy — bỏ qua"; return 0; }
  [[ -n "$ctxs" ]] || ctxs="$(for f in "$dir"/*.xml; do [[ -f "$f" ]] && basename "$f" .xml; done)"
  out="$base/logs/catalina.out"
  for c in $ctxs; do
    f="$dir/$c.xml"; [[ -f "$f" ]] || { echo "[$name] không có context /$c"; continue; }
    off=$(wc -c < "$out" | tr -d ' '); touch "$f"; ok=""
    for ((t=0; t<${RELOAD_WAIT:-90}; t+=2)); do
      sleep 2
      if tail -c +"$((off+1))" "$out" | grep -q "Deployment of deployment descriptor \[$f\] has finished"; then ok=1; break; fi
    done
    if [[ -z "$ok" ]]; then echo "[$name] /$c: chưa thấy redeploy sau ${RELOAD_WAIT:-90}s — xem log-$name.sh"
    elif tail -c +"$((off+1))" "$out" | grep -qE "SEVERE|NoSuchFileException|Context \[/$c\] startup failed"; then echo "[$name] /$c: redeploy XONG nhưng có lỗi — xem log-$name.sh"
    else echo "[$name] /$c: redeploy OK"; fi
  done
}

case "$ACTION" in
  list) list_names; exit 0 ;;
  wrappers) gen_wrappers; exit 0 ;;
  start|stop|restart|status|log|sync|conf|clearlog|webapps) ;;
  reload) shift 2 2>/dev/null || shift $#; RELOAD_CTX="$*" ;;
  *) echo "Usage: $0 <start|stop|restart|status|log|sync|conf|clearlog|webapps> [name|all] [days]"
     echo "       $0 reload [name|all] [context ...]"
     echo "       $0 list | wrappers"; exit 1 ;;
esac

if [[ "$TARGET" == "all" ]]; then
  [[ "$ACTION" == "log" ]] && { echo "log cần tên instance"; exit 1; }
  rc=0; names=$(ordered_names); [[ "$ACTION" == "stop" ]] && names=$(echo "$names" | sed '1!G;h;$!d')
  for n in $names; do
    if ! run "$n"; then
      rc=1
      if [[ "$ACTION" == "start" || "$ACTION" == "restart" ]] && (( $(order_of "$n") < 10 )); then
        echo "[$n] là instance nền tảng (START_ORDER=$(order_of "$n") < 10) và start thất bại → dừng, không start các instance còn lại"; exit 1
      fi
    fi
  done; exit $rc
else
  run "$TARGET"
fi
